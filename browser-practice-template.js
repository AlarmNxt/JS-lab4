// Задача 1. Сумма элементов массива — пример полностью
const rawNumbers = prompt("Задача 1. Введите числа через пробел:");
const parts = rawNumbers.trim().split(" ");
const numbers = [];

for (const part of parts) {
  numbers.push(Number(part));
}

let sum = 0;
for (const number of numbers) {
  sum += number;
}

alert(`Сумма: ${sum}`);

